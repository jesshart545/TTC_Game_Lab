/**
 * The tool a demonstration runs on: the project's own enabled tool of that
 * type when one exists (its real config), otherwise a stand-in carrying the
 * tool's real built-in defaults from lib/game-tools — the same defaults a
 * new tool of that type starts with. Demonstrations never invent project
 * data, and demo interactions never write back to the project.
 */
export function demoTool(project: Project, type: GameToolType): { tool: GameTool; fromProject: boolean } {
  const own = (project.gameTools || []).find(tool => tool.type === type && tool.enabled)
    || (type === "wheel" && project.wheel?.enabled
      ? { id: "legacy-wheel", type: "wheel" as GameToolType, name: project.wheel.title || "Game Wheel", enabled: true, config: { title: project.wheel.title, segments: project.wheel.segments } }
      : undefined);
  if (own) return { tool: own, fromProject: true };
  return {
    tool: { id: `demo-${type}`, type, name: String(toolDefaults(type).title || type), enabled: true, config: { ...toolDefaults(type) } },
    fromProject: false,
  };
}

/** Every distinct segment set the project itself owns, for the wheel's "show me different segments" edit demo. */
export function projectWheelSegmentSets(project: Project): string[][] {
  const sets: string[][] = [];
  const push = (segments: unknown) => {
    if (!Array.isArray(segments) || !segments.length) return;
    const set = segments.map(String);
    if (!sets.some(existing => JSON.stringify(existing) === JSON.stringify(set))) sets.push(set);
  };
  for (const tool of project.gameTools || []) if (tool.type === "wheel" && tool.enabled) push(tool.config.segments);
  if (project.wheel?.enabled) push(project.wheel.segments);
  return sets;
}

/** The most recently added asset of a media kind (voice/music/sfx/image/video), or null. */
export function latestAssetOfKind(project: Project, kind: AssetKind): ProjectAsset | null {
  const matches = (project.assets || []).filter(asset => assetCategory(asset) === kind && (asset.url || asset.storageKey));
  return matches.length ? matches[matches.length - 1] : null;
}

/** The project's background image asset, else its first image asset, else null. */
export function backdropAsset(project: Project): ProjectAsset | null {
  const images = (project.assets || []).filter(asset => assetCategory(asset) === "image" && asset.url);
  return images.find(asset => asset.role === "background") || images[0] || null;
}

