const assert = require('node:assert/strict');
const load = require('./load.cjs');
const { workshopGuidance } = load('lib/workshop-guidance.ts');
const { createProject } = load('lib/project.ts');
const blank = createProject('A local clarity test');
const original = JSON.stringify(blank);
const task = (project, section) => workshopGuidance(project, section);
assert.equal(task(blank, 0).nextActions[0].intent, 'plan', 'An opened but empty plan must still guide writing, not pretend completion.');
assert.equal(task({ ...blank, name: 'Song quiz', gamePlan: { theme: 'Name the song from a clue' } }, 0).nextActions[0].intent, 'materials');
assert.equal(task(blank, 1).nextActions[0].intent, 'media');
const media = { ...blank, assets: [{ name: 'Backdrop', type: 'image/png', storageKey: 'local-backdrop' }] };
assert.equal(task(media, 1).nextActions[0].intent, 'tools', 'A saved background must not trigger the same Create background recommendation again.');
assert(task(media, 1).nextDescription.includes('1 media file'));
assert.equal(task(media, 1).nextActions.find(action => action.label === 'Create more media').intent, 'generate', 'General media must not silently route to background creation.');
const game = { ...media, gameTools: [{ id: 'coin', type: 'coin-toss', name: 'Coin toss', enabled: true, config: {} }] };
assert.equal(task(game, 1).nextActions[0].intent, 'build');
assert(task(game, 1).nextDescription.includes('1 game tool'));
assert.equal(task({ ...blank, assets: [{ name: 'Unloaded placeholder', type: 'image/png' }], gameTools: [{ enabled: false }] }, 1).nextActions[0].intent, 'media', 'Empty placeholders and disabled templates are not counted as usable saved pieces.');
assert.equal(task(blank, 2).nextActions[0].intent, 'scene');
assert(task(blank, 2).nextDescription.includes('optional'));
assert(task(blank, 2).nextActions.some(action => action.intent === 'build'), 'Users can skip optional scenes.');
const scenes = { ...game, compositions: [{ id: 'intro', name: 'Intro', clips: [], duration: 2 }] };
assert.equal(task(scenes, 2).nextActions[0].intent, 'scenes');
assert(task(scenes, 2).nextDescription.includes('does not mean tested'));
assert.equal(JSON.stringify(blank), original, 'Guidance is pure and cannot change project or published state.');
console.log('PASS: relevant per-section guidance, real saved-content counts, no repeated background recommendation, no false completion, and optional scenes.');
